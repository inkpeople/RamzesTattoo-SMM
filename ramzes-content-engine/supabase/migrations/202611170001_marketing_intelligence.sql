-- RAMZES AI stage 2: private business analytics and durable memory.
-- Apply only to the dedicated RAMZES AI project after the owner creates it.
-- Tables are server-only: no anon/authenticated grants, RLS enabled, service_role only.
create table if not exists public.ramzes_content_engine_leads (
  id bigint generated by default as identity primary key,
  telegram_user_id bigint not null,
  created_at timestamptz not null default now(),
  source_platform text not null default 'unknown',
  stage text not null default 'new' check (stage in ('new','qualified','consultation','booked','completed','lost')),
  lead_data jsonb not null default '{}'::jsonb,
  score jsonb not null default '{}'::jsonb,
  unique (id, telegram_user_id)
);
create index if not exists ramzes_ce_leads_owner_created_idx
  on public.ramzes_content_engine_leads (telegram_user_id, created_at desc);

create table if not exists public.ramzes_content_engine_bookings (
  id bigint generated by default as identity primary key,
  telegram_user_id bigint not null,
  lead_id bigint,
  created_at timestamptz not null default now(),
  session_date date not null,
  status text not null default 'booked' check (status in ('booked','completed','cancelled','no_show')),
  amount numeric(14,2),
  source_platform text not null default 'unknown',
  constraint ramzes_ce_booking_lead_owner_fk
    foreign key (lead_id, telegram_user_id)
    references public.ramzes_content_engine_leads (id, telegram_user_id)
);
create index if not exists ramzes_ce_bookings_owner_date_idx
  on public.ramzes_content_engine_bookings (telegram_user_id, session_date desc);

create table if not exists public.ramzes_content_engine_publications (
  id bigint generated by default as identity primary key,
  telegram_user_id bigint not null,
  created_at timestamptz not null default now(),
  published_at timestamptz,
  platform text not null default 'unknown',
  content_type text not null default 'post',
  topic text not null default '',
  hook text not null default '',
  url text not null default '',
  status text not null default 'published' check (status in ('draft','scheduled','published','archived')),
  content_hash text not null default '',
  unique (telegram_user_id, content_hash)
);
create index if not exists ramzes_ce_publications_owner_date_idx
  on public.ramzes_content_engine_publications (telegram_user_id, published_at desc);

alter table public.ramzes_content_engine_metrics
  add column if not exists publication_id bigint references public.ramzes_content_engine_publications(id) on delete set null;
create index if not exists ramzes_ce_metrics_publication_idx
  on public.ramzes_content_engine_metrics (telegram_user_id, publication_id, captured_at desc);

create table if not exists public.ramzes_content_engine_memory_events (
  id bigint generated by default as identity primary key,
  telegram_user_id bigint not null,
  created_at timestamptz not null default now(),
  memory_type text not null check (memory_type in ('brand_fact','preference','decision','campaign','learning','workflow')),
  content text not null,
  source text not null default 'owner',
  confidence numeric(4,3) not null default 1.0 check (confidence between 0 and 1),
  confirmed boolean not null default true,
  metadata jsonb not null default '{}'::jsonb
);
create index if not exists ramzes_ce_memory_owner_date_idx
  on public.ramzes_content_engine_memory_events (telegram_user_id, created_at desc);

create table if not exists public.ramzes_content_engine_market_sources (
  id bigint generated by default as identity primary key,
  telegram_user_id bigint not null,
  created_at timestamptz not null default now(),
  source_url text not null,
  source_type text not null default 'public_web',
  title text not null default '',
  excerpt text not null default '',
  published_at text not null default '',
  content_hash text not null default '',
  unique (telegram_user_id, source_url)
);
create index if not exists ramzes_ce_market_owner_date_idx
  on public.ramzes_content_engine_market_sources (telegram_user_id, created_at desc);

create table if not exists public.ramzes_content_engine_agent_runs (
  id bigint generated by default as identity primary key,
  telegram_user_id bigint not null,
  created_at timestamptz not null default now(),
  task_type text not null,
  agent_ids jsonb not null default '[]'::jsonb,
  status text not null default 'completed',
  outputs jsonb not null default '{}'::jsonb
);
create index if not exists ramzes_ce_agent_runs_owner_date_idx
  on public.ramzes_content_engine_agent_runs (telegram_user_id, created_at desc);

alter table public.ramzes_content_engine_leads enable row level security;
alter table public.ramzes_content_engine_bookings enable row level security;
alter table public.ramzes_content_engine_publications enable row level security;
alter table public.ramzes_content_engine_memory_events enable row level security;
alter table public.ramzes_content_engine_market_sources enable row level security;
alter table public.ramzes_content_engine_agent_runs enable row level security;

revoke all on table
  public.ramzes_content_engine_leads,
  public.ramzes_content_engine_bookings,
  public.ramzes_content_engine_publications,
  public.ramzes_content_engine_memory_events,
  public.ramzes_content_engine_market_sources,
  public.ramzes_content_engine_agent_runs
from anon, authenticated;
grant select, insert, update, delete on table
  public.ramzes_content_engine_leads,
  public.ramzes_content_engine_bookings,
  public.ramzes_content_engine_publications,
  public.ramzes_content_engine_memory_events,
  public.ramzes_content_engine_market_sources,
  public.ramzes_content_engine_agent_runs
to service_role;
grant usage, select on sequence
  public.ramzes_content_engine_leads_id_seq,
  public.ramzes_content_engine_bookings_id_seq,
  public.ramzes_content_engine_publications_id_seq,
  public.ramzes_content_engine_memory_events_id_seq,
  public.ramzes_content_engine_market_sources_id_seq,
  public.ramzes_content_engine_agent_runs_id_seq
to service_role;
