-- RAMZES CONTENT ENGINE: initial persistent storage schema
-- Run in the NEW RAMZES AI Supabase project only.
-- The bot uses a server-side service-role key. Never expose it to Telegram clients,
-- browser code, GitHub, or public frontend bundles.

create table if not exists public.ramzes_content_engine_chat_history (
  telegram_user_id bigint primary key,
  chat_id bigint not null,
  messages jsonb not null default '[]'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.ramzes_content_engine_brand_profile (
  telegram_user_id bigint primary key,
  profile jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.ramzes_content_engine_content_library (
  id bigint generated by default as identity primary key,
  telegram_user_id bigint not null,
  chat_id bigint not null,
  platform text not null default 'multi',
  content_type text not null default 'content_pack',
  pillar text not null default 'personal_brand',
  topic text not null default '',
  hook text not null default '',
  body text not null,
  status text not null default 'draft',
  content_hash text not null,
  created_at timestamptz not null default now(),
  constraint ramzes_content_engine_content_owner_hash_unique
    unique (telegram_user_id, content_hash)
);

create index if not exists ramzes_content_engine_content_owner_created_idx
  on public.ramzes_content_engine_content_library (telegram_user_id, created_at desc);

create table if not exists public.ramzes_content_engine_metrics (
  id bigint generated by default as identity primary key,
  telegram_user_id bigint not null,
  platform text not null default 'unknown',
  captured_at timestamptz not null default now(),
  views bigint,
  likes bigint,
  comments bigint,
  reposts bigint,
  saves bigint,
  profile_visits bigint,
  followers_gained bigint,
  inbound_messages bigint,
  bookings bigint,
  ad_spend numeric(14,2),
  notes text not null default '',
  raw_metrics jsonb not null default '{}'::jsonb
);

create index if not exists ramzes_content_engine_metrics_owner_date_idx
  on public.ramzes_content_engine_metrics (telegram_user_id, captured_at desc);

-- No anon/authenticated policies are created: RLS denies client access.
-- The trusted bot backend accesses these tables with SUPABASE_SERVICE_ROLE_KEY.
alter table public.ramzes_content_engine_chat_history enable row level security;
alter table public.ramzes_content_engine_brand_profile enable row level security;
alter table public.ramzes_content_engine_content_library enable row level security;
alter table public.ramzes_content_engine_metrics enable row level security;

comment on table public.ramzes_content_engine_chat_history is 'Private RAMZES AI Telegram conversation history.';
comment on table public.ramzes_content_engine_brand_profile is 'Private RAMZES AI confirmed brand facts and voice.';
comment on table public.ramzes_content_engine_content_library is 'Private generated content archive with duplicate detection.';
comment on table public.ramzes_content_engine_metrics is 'Private social performance metrics entered by the owner.';
