def _format_telegram_line(line):
    """Convert common Markdown emphasis into safe Telegram HTML."""
    import html
    raw = line.rstrip()
    if not raw:
        return ""
    heading = re.match(r"^\s{0,3}#{1,6}\s+(.+)$", raw)
    is_heading = bool(heading)
    if heading:
        raw = heading.group(1)
    bullet = re.match(r"^\s*[-*+]\s+(.+)$", raw)
    if bullet:
        raw = "• " + bullet.group(1)
    escaped = html.escape(raw, quote=False)
    escaped = re.sub(r"&lt;(/?)(b|i|u|s|code)&gt;", r"<\1\2>", escaped, flags=re.IGNORECASE)
    escaped = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", escaped)
    escaped = re.sub(r"__(.+?)__", r"<b>\1</b>", escaped)
    escaped = re.sub(r"(?<!\*)\*(?!\s)(.+?)(?<!\s)\*(?!\*)", r"<i>\1</i>", escaped)
    escaped = re.sub(r"(?<![A-Za-zА-Яа-яЁё0-9])_(.+?)_(?![A-Za-zА-Яа-яЁё0-9])", r"<i>\1</i>", escaped)
    if is_heading:
        escaped = "<b>" + escaped + "</b>"
    return escaped


def _telegram_html(text):
    return "\n".join(_format_telegram_line(line) for line in str(text or "").splitlines())


