            action = labels[text]
            if action == "reset":
                with memory_lock:
                    memory.pop(str(chat_id), None)
                clear_chat_history(OWNER_ID or chat_id)
                send_text(chat_id, "История диалога очищена. Библиотека контента и профиль бренда сохранены.")
