@app.post("/telegram")
def telegram_webhook():
    # Telegram webhook must always be authenticated; never accept an open endpoint.
    if not WEBHOOK_SECRET:
        log.error("Webhook request rejected: TELEGRAM_WEBHOOK_SECRET is not configured.")
        return jsonify({"ok": False, "error": "webhook_not_configured"}), 503
    supplied = request.headers.get("X-Telegram-Bot-Api-Secret-Token", "")
    if not hmac.compare_digest(supplied, WEBHOOK_SECRET):
        return jsonify({"ok": False}), 403
    update = request.get_json(silent=True) or {}
    try:
        dispatch_status = dispatcher.submit(pool, process_update, update)
    except Exception:
        log.exception("Could not queue Telegram update")
        return jsonify({"ok": False, "error": "queue_unavailable"}), 503
    if dispatch_status == "full":
        return jsonify({"ok": False, "error": "queue_full"}), 503
    return jsonify({"ok": True, "duplicate": dispatch_status == "duplicate"})


def configure_webhook():
    if not BOT_TOKEN or not APP_URL or not WEBHOOK_SECRET:
        log.warning("Webhook not configured: set TELEGRAM_BOT_TOKEN, TELEGRAM_WEBHOOK_SECRET and deploy URL.")
        return
    try:
        result = tg("setWebhook", {
            "url": f"{APP_URL}/telegram",
            "secret_token": WEBHOOK_SECRET,
            "allowed_updates": ["message", "callback_query"],
            "drop_pending_updates": False
        })
        log.info("Telegram webhook configured: %s", result)
    except requests.HTTPError as exc:
        # Never log the request URL: Telegram bot URLs contain the bot token.
        status = exc.response.status_code if exc.response is not None else "unknown"
        body = exc.response.text[:1000] if exc.response is not None else "No response body"
        log.error("Telegram webhook rejected (HTTP %s): %s", status, body)
    except Exception:
        log.exception("Could not configure Telegram webhook")


